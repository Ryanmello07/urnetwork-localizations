// Per-platform codegen from the canonical store.
//
//   node gen/generate.mjs            write every target
//   node gen/generate.mjs --check    regenerate into a temp dir and fail on drift
//   node gen/generate.mjs android    one target only
//
// Every emitted file is a build artifact: edit keys/*.yaml, never the output.
import fs from "fs";
import os from "os";
import path from "path";
import {
	ROOT, LOCALES, ANDROID_LOCALE_DIR, APPLE_LOCALE, WINDOWS_LOCALE, LINUX_LOCALE,
	CLDR_CATEGORIES, CAT_ORDER, GETTEXT_PLURALS, loadStore, lowerAndroid, lowerApple,
	lowerCpp, androidEscape, xmlText, poEscape, collate, comment, isDead, isCatalogFreeOnly,
	isTaggedFor,
} from "./store.mjs";

const BANNER = "Generated by @urnetwork/localizations (gen/generate.mjs). DO NOT EDIT.";

// ------------------------------------------------------------------- android
function android(keys) {
	const out = {};
	const mine = keys.filter((k) => k.platforms.includes("android"));
	for (const [loc, dir] of Object.entries(ANDROID_LOCALE_DIR)) {
		const L = [];
		for (const k of mine) {
			if (k.plurals) continue;
			if (!k.translatable && loc !== "en") continue;   // never translated: base only
			const v = k.localizations[loc];
			if (v == null) continue;
			const attr = !k.translatable ? ' translatable="false"' : "";
			L.push(`    <string name="${k.id}"${attr}>${androidEscape(lowerAndroid(v, k))}</string>`);
		}
		for (const k of mine) {
			if (!k.plurals) continue;
			const v = k.localizations[loc];
			if (v == null) continue;
			L.push(`    <plurals name="${k.id}">`);
			for (const cat of CAT_ORDER) {
				if (v[cat] == null) continue;
				L.push(`        <item quantity="${cat}">${androidEscape(lowerAndroid(v[cat], k))}</item>`);
			}
			L.push("    </plurals>");
		}
		out[`android/app/app/src/main/res/${dir}/strings.xml`] =
			`<?xml version="1.0" encoding="utf-8"?>\n<!-- ${BANNER} -->\n<resources>\n${L.join("\n")}\n</resources>\n`;
	}
	return out;
}

// --------------------------------------------------------------------- apple
// Hand-serialised to match xcode's writer exactly: 2-space indent, " : "
// separators, alphabetical member order, `{\n\n}` for empty objects, no
// trailing newline. (JSON.stringify also reorders integer-like keys such as
// "0", which would corrupt the catalog's ordering.)
const J = (s) => JSON.stringify(s);

function appleUnit(value, ind) {
	return `{\n${ind}  "state" : "translated",\n${ind}  "value" : ${J(value)}\n${ind}}`;
}

function apple(keys) {
	const mine = keys.filter((k) => k.platforms.includes("apple"));
	mine.sort((a, b) => collate(a.source, b.source));
	const entries = mine.map((k) => {
		const members = [];
		if (comment(k)) members.push([`"comment"`, J(comment(k))]);
		if (k.deprecated.includes("apple")) members.push([`"extractionState"`, J("stale")]);
		if (k.description_auto) members.push([`"isCommentAutoGenerated"`, "true"]);

		if (k.translatable) {
			const locs = Object.keys(k.localizations)
				.filter((l) => APPLE_LOCALE[l])
				.sort((a, b) => collate(APPLE_LOCALE[a], APPLE_LOCALE[b]));
			if (locs.length) {
				const L = locs.map((l) => {
					const v = k.localizations[l];
					let body;
					if (k.plurals) {
						const cats = CAT_ORDER.filter((c) => v[c] != null);
						const V = cats
							.map((c) => `            "${c}" : {\n              "stringUnit" : ${appleUnit(lowerApple(v[c], k), "              ")}\n            }`)
							.join(",\n");
						body = `{\n          "variations" : {\n            "plural" : {\n${V}\n            }\n          }\n        }`;
					} else {
						body = `{\n          "stringUnit" : ${appleUnit(lowerApple(v, k), "          ")}\n        }`;
					}
					return `        ${J(APPLE_LOCALE[l])} : ${body}`;
				}).join(",\n");
				members.push([`"localizations"`, `{\n${L}\n      }`]);
			}
		} else {
			members.push([`"shouldTranslate"`, "false"]);
		}

		members.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
		if (!members.length) return `    ${J(k.source)} : {\n\n    }`;
		const body = members.map(([n, v]) => `      ${n} : ${v}`).join(",\n");
		return `    ${J(k.source)} : {\n${body}\n    }`;
	});
	const json =
		`{\n  "sourceLanguage" : "en",\n  "strings" : {\n${entries.join(",\n")}\n  },\n  "version" : "1.1"\n}`;
	return { "apple/app/network/Shared/Resources/Localizable.xcstrings": json };
}

// ------------------------------------------------------- desktop tagged keys
// Windows and Linux carry every live key, so a lookup of a key the store does
// not tag for the app still finds its text -- until the platforms the key is
// tagged for retire it, it goes dead and leaves the desktop catalogs (how the
// Linux Earnings page lost net_points_earned). Each desktop app therefore also
// gets the ids of the keys tagged for it, one per line, and its catalog test
// fails on a lookup whose key is not among them, and on one among them that no
// lookup uses (a stale tag keeps its key alive for nothing).
export function taggedKeyList(keys, platform) {
	const ids = keys.filter((k) => isTaggedFor(k, platform)).map((k) => k.id).sort();
	return `# ${BANNER}\n# The store keys tagged ${platform}: exactly the keys the app looks up.\n${ids.join("\n")}\n`;
}

// ------------------------------------------------------------------- windows
// MRT .resw, keyed by id. Plural categories become `<id>.<category>` entries;
// Localization.h picks one with ResourceLoader + the CLDR rule.
const RESW_HEADER = `  <xsd:schema id="root" xmlns="" xmlns:xsd="http://www.w3.org/2001/XMLSchema" xmlns:msdata="urn:schemas-microsoft-com:xml-msdata">
    <xsd:import namespace="http://www.w3.org/XML/1998/namespace" />
    <xsd:element name="root" msdata:IsDataSet="true">
      <xsd:complexType>
        <xsd:choice maxOccurs="unbounded">
          <xsd:element name="data">
            <xsd:complexType>
              <xsd:sequence>
                <xsd:element name="value" type="xsd:string" minOccurs="0" msdata:Ordinal="1" />
                <xsd:element name="comment" type="xsd:string" minOccurs="0" msdata:Ordinal="2" />
              </xsd:sequence>
              <xsd:attribute name="name" type="xsd:string" msdata:Ordinal="1" />
              <xsd:attribute name="type" type="xsd:string" msdata:Ordinal="3" />
              <xsd:attribute name="mimetype" type="xsd:string" msdata:Ordinal="4" />
              <xsd:attribute ref="xml:space" />
            </xsd:complexType>
          </xsd:element>
          <xsd:element name="resheader">
            <xsd:complexType>
              <xsd:sequence>
                <xsd:element name="value" type="xsd:string" minOccurs="0" msdata:Ordinal="1" />
              </xsd:sequence>
              <xsd:attribute name="name" type="xsd:string" use="required" />
            </xsd:complexType>
          </xsd:element>
        </xsd:choice>
      </xsd:complexType>
    </xsd:element>
  </xsd:schema>
  <resheader name="resmimetype">
    <value>text/microsoft-resx</value>
  </resheader>
  <resheader name="version">
    <value>2.0</value>
  </resheader>
  <resheader name="reader">
    <value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>
  </resheader>
  <resheader name="writer">
    <value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>
  </resheader>`;

function windows(keys) {
	const out = {};
	for (const loc of LOCALES) {
		const L = [];
		for (const k of keys) {
			if (isDead(k) || isCatalogFreeOnly(k)) continue;
			if (!k.translatable && loc !== "en") continue;
			const v = k.localizations[loc];
			if (v == null) continue;
			const emit = (name, text) => {
				L.push(`  <data name="${name}" xml:space="preserve">`);
				L.push(`    <value>${xmlText(lowerCpp(text, k))}</value>`);
				if (comment(k)) L.push(`    <comment>${xmlText(comment(k).replace(/\n/g, " "))}</comment>`);
				L.push("  </data>");
			};
			if (k.plurals) {
				// MakePri builds one resource map across all language qualifiers. If
				// Arabic introduces e.g. `.zero` but the neutral English map has no
				// resource with that name, PRI263 warns that lookup can throw for a
				// user whose preferred-language fallback misses Arabic. English CLDR
				// itself only selects one/other, so emit neutral names for every CLDR
				// category and use `other` as the semantically correct fallback.
				for (const cat of CAT_ORDER) {
					const text = v[cat] ?? (loc === "en" ? v.other : null);
					if (text != null) emit(`${k.id}.${cat}`, text);
				}
			} else {
				emit(k.id, v);
			}
		}
		out[`windows/app/src/App/Strings/${WINDOWS_LOCALE[loc]}/Resources.resw`] =
			`<?xml version="1.0" encoding="utf-8"?>\n<!-- ${BANNER} -->\n<root>\n${RESW_HEADER}\n${L.join("\n")}\n</root>\n`;
	}
	out["windows/app/src/App/Strings/windows-keys.txt"] = taggedKeyList(keys, "windows");
	return out;
}

// --------------------------------------------------------------------- linux
// gettext. msgid is the english source; msgctxt is the key id, which is what
// disambiguates the keys that legitimately share english text (e.g. "Name" is
// both name_label and device_name_label).
function poEntry(k, loc, isPot) {
	const L = [];
	if (comment(k)) for (const line of comment(k).split("\n")) L.push(`#. ${line}`);
	L.push(`msgctxt "${poEscape(k.id)}"`);
	const en = k.localizations.en;
	// an untranslatable key (product names, symbols, numeric formats) ships its
	// english source in every catalog so the app resolves it through the same
	// pgettext lookup instead of falling back to a literal in the code
	const v = loc === "en" || !k.translatable ? en : k.localizations[loc];
	if (k.plurals) {
		const [, order] = GETTEXT_PLURALS[loc] || GETTEXT_PLURALS.en;
		L.push(`msgid "${poEscape(lowerCpp(en.one ?? en.other, k))}"`);
		L.push(`msgid_plural "${poEscape(lowerCpp(en.other, k))}"`);
		order.forEach((cat, i) => {
			const t = isPot || !v ? "" : lowerCpp(v[cat] ?? v.other, k);
			L.push(`msgstr[${i}] "${poEscape(t)}"`);
		});
	} else {
		L.push(`msgid "${poEscape(lowerCpp(en, k))}"`);
		L.push(`msgstr "${isPot || v == null ? "" : poEscape(lowerCpp(v, k))}"`);
	}
	return L.join("\n");
}

function linux(keys) {
	const out = {};
	const header = (loc, isPot) => {
		const [forms] = GETTEXT_PLURALS[loc] || GETTEXT_PLURALS.en;
		return [
			`# ${BANNER}`,
			'msgid ""',
			'msgstr ""',
			'"Project-Id-Version: urnetwork\\n"',
			'"MIME-Version: 1.0\\n"',
			'"Content-Type: text/plain; charset=UTF-8\\n"',
			'"Content-Transfer-Encoding: 8bit\\n"',
			'"Last-Translator: URnetwork <support@ur.io>\\n"',
			'"Language-Team: URnetwork\\n"',
			`"Language: ${isPot ? "" : LINUX_LOCALE[loc]}\\n"`,
			`"Plural-Forms: ${forms}\\n"`,
		].join("\n");
	};
	const body = (loc, isPot) =>
		keys
			.filter((k) => !isDead(k) && !isCatalogFreeOnly(k))
			.filter((k) => isPot || !k.translatable || k.localizations[loc] != null)
			.map((k) => poEntry(k, loc, isPot))
			.join("\n\n");
	out["linux/app/po/urnetwork.pot"] = `${header("en", true)}\n\n${body("en", true)}\n`;
	for (const loc of LOCALES)
		out[`linux/app/po/${LINUX_LOCALE[loc]}.po`] = `${header(loc, false)}\n\n${body(loc, false)}\n`;
	out["linux/app/po/LINGUAS"] = LOCALES.map((l) => LINUX_LOCALE[l]).sort().join("\n") + "\n";
	out["linux/app/po/linux-keys.txt"] = taggedKeyList(keys, "linux");
	return out;
}

// ---------------------------------------------------------------------- main
const TARGETS = { android, apple, windows, linux };

export function build(names = Object.keys(TARGETS)) {
	const keys = loadStore();
	const files = {};
	for (const n of names) Object.assign(files, TARGETS[n](keys));
	return files;
}

// importable (verify-lossless.mjs reads the generated content straight out of
// build()); only act as a CLI when run directly.
const isMain = process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(new URL(import.meta.url).pathname);
if (!isMain) { /* imported */ } else {

const args = process.argv.slice(2);
const check = args.includes("--check");
const names = args.filter((a) => !a.startsWith("--"));
const targets = names.length ? names : Object.keys(TARGETS);
for (const t of targets)
	if (!TARGETS[t]) { console.error(`unknown target: ${t}`); process.exit(2); }

const files = build(targets);

if (check) {
	const drift = [];
	for (const [rel, content] of Object.entries(files)) {
		const p = path.join(ROOT, rel);
		const cur = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
		if (cur !== content) drift.push(rel);
	}
	if (drift.length) {
		console.error(`localizations: ${drift.length} generated file(s) differ from the store:`);
		for (const d of drift) console.error("  " + d);
		console.error("\nrun `npm run gen` and commit the result.");
		process.exit(1);
	}
	console.log(`localizations: ${Object.keys(files).length} generated files are up to date`);
} else {
	let n = 0;
	for (const [rel, content] of Object.entries(files)) {
		const p = path.join(ROOT, rel);
		fs.mkdirSync(path.dirname(p), { recursive: true });
		const cur = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
		if (cur !== content) { fs.writeFileSync(p, content); n++; }
	}
	console.log(`localizations: wrote ${n} of ${Object.keys(files).length} files (${targets.join(", ")})`);
}

}   // isMain
